#!/usr/bin/env python3
"""Generate src/player_state.hpp from the Geode bindings' PlayerObject members.

Usage: gen_player_state.py <path to bindings/2.2091/GeometryDash.bro> > src/player_state.hpp

Every value-typed member of PlayerObject is copied. Pointer members are skipped
(child sprites, particles, layers), except pointers into level objects, which the
physics reads (slopes, ground objects, portals, the dash ring).
"""
import re, sys

KEEP_POINTERS = {"GameObject*", "DashRingObject*"}
SKIP = {
    "m_pendingCheckpoint",      # GD-managed checkpoint, not physics
    "m_iconRequestID",          # icon loading
    "m_currentRobotAnimation",  # sprite animation name
    "m_isSecondPlayer",         # identity, never changes
}

src = open(sys.argv[1], encoding="utf-8").read().splitlines()
start = next(i for i, l in enumerate(src) if l.startswith("class PlayerObject "))
end = next(i for i in range(start + 1, len(src)) if src[i].startswith("}"))

fields = []
for line in src[start:end]:
    line = line.split("//")[0].strip()
    if not line.endswith(";") or "(" in line or line.startswith(("class", "static")):
        continue
    m = re.match(r"^(.+?)\s+(m_\w+)(\[\d+\])?;$", line)
    if not m:
        continue
    ty, name, arr = m.group(1).strip(), m.group(2), m.group(3)
    if arr or name in SKIP or "PAD" in ty:
        continue
    if ty.endswith("*") and ty.replace(" ", "") not in KEEP_POINTERS:
        continue
    fields.append((ty, name))

out = []
w = out.append
w("// GENERATED by tools/gen_player_state.py from geode-sdk/bindings (2.2091). Do not edit by hand.")
w("#pragma once")
w("#include <Geode/Geode.hpp>")
w("")
w("namespace pf {")
w("struct PlayerFields {")
for ty, name in fields:
    w(f"    {ty} {name}{{}};")
w("};")
w("")
w("inline void savePlayerFields(PlayerObject* p, PlayerFields& s) {")
for _, name in fields:
    w(f"    s.{name} = p->{name};")
w("}")
w("")
w("inline void loadPlayerFields(PlayerObject* p, PlayerFields const& s) {")
for _, name in fields:
    w(f"    p->{name} = s.{name};")
w("}")
w("} // namespace pf")
print("\n".join(out))
print(f"{len(fields)} fields", file=sys.stderr)
